export const FORBIDDEN_WORDS = [
  "ارزان‌ترین",
  "باورنکردنی",
  "فوق‌العاده‌ترین",
  "بهترین دنیا",
  "بهترین",
  "بدون رقیب",
  "بی‌رقیب",
  "محشر",
  "خفن",
  "ترکوند",
  "عجله کنید",
  "از دستش ندهید",
  "فقط امروز",
  "فرصت طلایی",
  "شاهکار بی‌نظیر",
  "قدرتمندترین",
  "اینجا کلیک کنید",
] as const;

export function findForbiddenWords(text: string): string[] {
  return FORBIDDEN_WORDS.filter((word) => text.includes(word));
}
